import assert from 'node:assert/strict';
import { mergeReceiptCache, preferredReceiptNumber } from '../lib/posReceiptCache.js';
const now = Date.parse('2026-10-09T08:00:00Z');
const old = { receipt_number: 'OLD', created_at: '2026-10-02T08:00:00Z' };
const today = { receipt_number: 'TODAY', created_at: '2026-10-09T04:00:00Z' };
const previous = { rows: [old, today], itemRows: [{ id: 'local', receipt_number: 'TODAY', item: 'Latte' }] };
const synced = mergeReceiptCache(previous, { rows: [old] }, now);
assert.deepEqual(synced.rows.map(row => row.receipt_number), ['TODAY', 'OLD']);
assert.equal(preferredReceiptNumber(synced.rows, 'OLD'), 'TODAY');
assert.equal(preferredReceiptNumber(synced.rows, 'TODAY'), 'TODAY');
const completed = mergeReceiptCache(previous, { rows: [today], itemRows: [{ id: 'server', receipt_number: 'TODAY', item: 'Latte' }] }, now);
assert.equal(completed.itemRows.length, 1);
const refunded = mergeReceiptCache(completed, { rows: [{ ...today, status: 'Refunded' }] }, now);
assert.equal(refunded.rows[0].status, 'Refunded');
assert.equal(refunded.itemRows.length, 1);
const latest = { ...today, updated_at: '2026-10-09T06:00:00Z', status: 'Refunded' };
assert.equal(mergeReceiptCache({ rows: [latest] }, { rows: [{ ...today, updated_at: '2026-10-09T05:00:00Z', status: 'Closed' }] }, now).rows[0].status, 'Refunded');
assert.equal(mergeReceiptCache({ rows: [{ ...old, created_at: '2026-09-01T00:00:00Z' }] }, {}, now).rows.length, 0);
console.log('PASS: newest receipt first, local sale retained during slow sync, stale-day selection, item replacement, refund updates, bounded history');
