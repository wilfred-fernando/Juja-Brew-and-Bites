const {loadEnvConfig}=require('@next/env');
const {Client}=require('pg');
const fs=require('node:fs');
const assert=require('node:assert/strict');
const {randomUUID}=require('node:crypto');
loadEnvConfig(process.cwd());
(async()=>{
  const db=new Client({connectionString:process.env.DATABASE_URL,ssl:{rejectUnauthorized:false}});
  await db.connect();
  try {
    await db.query('begin');
    const sql=fs.readFileSync('supabase/migrations/20261101090000_change_accepted_web_order_type.sql','utf8').replace(/^begin;\s*/,'').replace(/commit;\s*$/,'');
    await db.query(sql);
    const actor=(await db.query("select id,store_id from profiles where role='cashier' and store_id is not null limit 1")).rows[0];
    assert(actor);
    await db.query("select set_config('request.jwt.claim.sub',$1,true)",[actor.id]);
    const id=randomUUID();
    const items=[{id:'existing-item',name:'Drink',quantity:2,kds_completed:true}];
    let order=(await db.query(`insert into web_orders(id,store_id,branch_id,customer_name,status,order_status,accepted_at,items,subtotal,total,payment_method,payment_status,dining_option,fulfillment_type,delivery_fee) values($1,$2::uuid,$2::text,'Rollback type test','preparing','preparing',now(),$3,200,200,'Cash','paid','TAKEOUT','TAKEOUT',25) returning *`,[id,actor.store_id,JSON.stringify(items)])).rows[0];
    for(const source of [id,id+':batch:test']) await db.query(`insert into kds_tickets(source_type,source_id,store_id,items,status,dining_option,fulfillment_type,total) values('web',$1,$2,$3,'preparing','ONLINE: TAKEOUT','TAKEOUT',200)`,[source,actor.store_id,JSON.stringify(items)]);
    order.updated_at=(await db.query('select updated_at::text stamp from web_orders where id=$1',[id])).rows[0].stamp;
    const mutate=async(type,address=null,stamp=order.updated_at,store=actor.store_id)=>(await db.query('select to_jsonb(change_pos_web_order_type($1,$2,$3,$4,$5)) row',[id,store,type,stamp,address])).rows[0].row;
    const reject=async(fn,pattern)=>{await db.query('savepoint denied');await assert.rejects(fn,pattern);await db.query('rollback to savepoint denied');};
    order=await mutate('DINE-IN');
    assert.equal(order.fulfillment_type,'DINE-IN');
    assert.equal(Number(order.total),200);
    assert.equal(Number(order.delivery_fee),25);
    assert.equal(order.status,'preparing');
    assert.equal(order.payment_status,'paid');
    assert.deepEqual(order.items,items);
    const cards=(await db.query("select items,status,dining_option from kds_tickets where source_id=$1 or source_id=$2",[id,id+':batch:test'])).rows;
    assert.equal(cards.length,2);
    for(const card of cards){assert.equal(card.status,'preparing');assert.deepEqual(card.items,items);assert.equal(card.dining_option,'ONLINE: DINE-IN');}
    await reject(()=>mutate('DELIVERY',''),/delivery address/);
    order=await mutate('DELIVERY','  Test delivery address  ');
    assert.equal(order.delivery_address,'Test delivery address');
    order=await mutate('TAKEOUT');
    assert.equal(order.delivery_address,'Test delivery address','Changing type preserves the recorded address');
    await reject(()=>mutate('DINE-IN',null,'2000-01-01T00:00:00Z'),/another device/);
    await reject(()=>mutate('DINE-IN',null,order.updated_at,'wrong-branch'),/Wrong POS branch/);
    await reject(()=>mutate('INVALID'),/Choose/);
    await db.query('savepoint charged');
    await db.query("update web_orders set receipt_number='TEST-CHARGED',status='completed',order_status='completed' where id=$1",[id]);
    await reject(()=>mutate('DINE-IN'),/accepted, uncharged/);
    await db.query('rollback to savepoint charged');
    await db.query('savepoint pending');
    await db.query("update web_orders set status='pending',order_status='pending',accepted_at=null where id=$1",[id]);
    await reject(()=>mutate('DINE-IN'),/accepted, uncharged/);
    await db.query('rollback to savepoint pending');
    await db.query('savepoint courier');
    await db.query("update web_orders set delivery_order_id='test-courier',delivery_status='assigned' where id=$1",[id]);
    order.updated_at=(await db.query('select updated_at::text stamp from web_orders where id=$1',[id])).rows[0].stamp;
    await reject(()=>mutate('DINE-IN'),/courier/);
    await db.query('rollback to savepoint courier');
    await db.query("select set_config('request.jwt.claim.sub',$1,true)",[randomUUID()]);
    await reject(()=>mutate('DINE-IN'),/Staff login/);
    await db.query('rollback');
    console.log('PASS (rollback): all types, required address, totals/items/payment preserved, existing KDS cards preserved, stale/branch/closed/pending/courier/auth guards');
  }catch(error){await db.query('rollback');throw error;}finally{await db.end();}
})().catch(error=>{console.error(error.message);process.exitCode=1;});
