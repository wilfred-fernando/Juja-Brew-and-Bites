import assert from 'node:assert/strict';
import {isWelcomeDrink,welcomeVoucherDiscount,welcomeVoucherSelectionError,welcomeVoucherSettlementError,welcomeVoucherPaidPartnerExclusions} from '../lib/posWelcomeVoucher.js';
const voucher={id:'welcome',reward_type:'welcome'};
const drink={cartItemId:'a',name:'Cheesecake Milk Tea',variantDetails:'Regular, 50%',unitPrice:109,quantity:2};
assert.equal(isWelcomeDrink(drink),true);
assert.equal(isWelcomeDrink({...drink,name:'Oreo Cheesecake Milk Tea'}),false);
assert.equal(isWelcomeDrink({...drink,variantDetails:'Large'}),false);
assert.equal(isWelcomeDrink({...drink,voided:true}),false);
assert.equal(welcomeVoucherSelectionError([drink],'a'),'');
assert.equal(welcomeVoucherDiscount(drink),109);
assert.equal(welcomeVoucherDiscount({...drink,quantity:3}),109);
assert.ok(welcomeVoucherSelectionError([{...drink,quantity:1}],'a'));
const separate=[{...drink,quantity:1},{...drink,cartItemId:'b',quantity:1,variantDetails:'Regular, 25%'}];
assert.equal(welcomeVoucherSelectionError(separate,'a'),'');
assert.ok(welcomeVoucherSelectionError([separate[0],{...separate[1],discountAmount:10}],'a'));
assert.ok(welcomeVoucherSelectionError([{...drink,discountAmount:10}],'a'));
const applied={...drink,appliedVoucher:voucher,_origDiscountAmount:0,discountAmount:109};
assert.equal(welcomeVoucherSettlementError([applied]),'');
assert.equal(welcomeVoucherSettlementError([{...applied,quantity:3}]),'');
assert.ok(welcomeVoucherSettlementError([{...applied,quantity:1}]));
assert.ok(welcomeVoucherSettlementError([{...applied,discountAmount:163.5,quantity:3}]));
assert.equal(welcomeVoucherSettlementError([{...applied,quantity:1},separate[1]]),'');
assert.ok(welcomeVoucherSettlementError([{...applied,quantity:1},{...separate[1],voided:true}]));
console.log('PASS: correct product/size, paid pair, one free drink cap, no stacking, and settlement revalidation.');
assert.equal(welcomeVoucherPaidPartnerExclusions([applied]).size,0);
const pair=[{...applied,quantity:1},separate[1]];
assert.equal(welcomeVoucherPaidPartnerExclusions(pair).get('b').amount,109);
assert.equal(welcomeVoucherPaidPartnerExclusions(separate).size,0);
assert.equal(welcomeVoucherPaidPartnerExclusions([...pair,{...drink,cartItemId:'c',quantity:1}]).size,1);
const partnerBulk=[{...applied,quantity:1},{...separate[1],quantity:3}];
assert.equal(welcomeVoucherPaidPartnerExclusions(partnerBulk).get('b').amount,109);
const eligibleTotal = cart => {
  const exclusions=welcomeVoucherPaidPartnerExclusions(cart);
  return cart.reduce((sum,line)=>sum+(line.appliedVoucher?.reward_type==='welcome'?0:
    Math.max(0,line.unitPrice*line.quantity-(exclusions.get(line.cartItemId)?.amount||0))),0);
};
assert.equal(eligibleTotal([applied]),0);
assert.equal(eligibleTotal(pair),0);
assert.equal(eligibleTotal([...pair,{cartItemId:'food',name:'Sandwich',unitPrice:150,quantity:1}]),150);
assert.equal(eligibleTotal(separate),218);
assert.equal(eligibleTotal(partnerBulk),218);
console.log('PASS: both Welcome Voucher drinks earn zero points; other purchases and voucher removal retain normal earning.');
